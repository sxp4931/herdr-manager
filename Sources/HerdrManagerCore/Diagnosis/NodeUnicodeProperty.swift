/// Unicode property names Node 22.23.2 accepts in `\p` and `\P`.
///
/// V8 12.4 looks the name up with ICU 78.2 (Unicode 17) and then requires
/// an exact alias. Case and underscores are significant. A lone name is a
/// general-category value, `Any` / `ASCII` / `Assigned`, or a binary
/// property on the allowlist in `regexp-parser.cc`. `name=value` is only
/// `General_Category`, `Script`, or `Script_Extensions`. The seven
/// properties of strings are legal only with the `v` flag, and `\P` of
/// one is not. `Hrkt` is a script alias whose set is empty, so Node
/// rejects it and it is not listed.
enum NodeUnicodeProperty {
    enum Kind: Equatable {
        case invalid
        case characters
        case strings
    }

    /// `value` is nil for a lone name. `sets` is the `v` flag.
    /// `negated` is `\P`. A property of strings is `strings` only when
    /// `v` is set and the escape is not negated; every other miss is
    /// `invalid`.
    static func kind(name: String, value: String?, sets: Bool, negated: Bool) -> Kind {
        if let value {
            if name.isEmpty || value.isEmpty { return .invalid }
            if generalCategoryProperties.contains(name) {
                return generalCategoryValues.contains(value) ? .characters : .invalid
            }
            if scriptProperties.contains(name) || scriptExtensionProperties.contains(name) {
                return scriptValues.contains(value) ? .characters : .invalid
            }
            return .invalid
        }
        if generalCategoryValues.contains(name) || loneCharacterProperties.contains(name) {
            return .characters
        }
        if stringProperties.contains(name) {
            if negated || !sets { return .invalid }
            return .strings
        }
        return .invalid
    }

    private static func names(_ text: String) -> Set<String> {
        var set: Set<String> = []
        for line in text.split(separator: "\n", omittingEmptySubsequences: true) {
            set.insert(String(line))
        }
        return set
    }

