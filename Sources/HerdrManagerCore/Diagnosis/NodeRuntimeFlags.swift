/// Node 22.23.2 options that reach a script, and the V8 flags that same
/// binary accepts. An argv word that is not in one of these sets is a
/// bad option: the process exits and the following path is not the program.
///
/// Node's own booleans accept `--flag`, `--flag=value`, and `--no-flag`.
/// V8 booleans accept `--flag`, `--no-flag`, and a single dash (`-harmony`),
/// and they reject `=`. V8 values accept only `--flag=value` (and `-flag=value`).
/// A separate word is not the value. The lists were taken from `node --help`
/// and `node --v8-options` on this runtime.
enum NodeRuntimeFlags {
    static let scriptBooleans: Set<String> = flags(scriptBooleanLines)
    static let printFlags: Set<String> = flags(printFlagLines)
    /// `--test=true` does not run the file. `--no-test=true` still does.
    static let equalsRejected: Set<String> = flags(equalsRejectedLines)
    static let v8Booleans: Set<String> = flags(v8BooleanLines)
    /// The positive form aborts before the file. `--no-` of it still runs.
    static let v8NegationOnly: Set<String> = flags(v8NegationOnlyLines)
    static let v8Values: Set<String> = flags(v8ValueLines)
    /// An empty `--flag=` exits. A non-empty value still names the script.
    static let v8EmptyEqualsExits: Set<String> = flags(v8EmptyEqualsExitsLines)

    private static func flags(_ text: String) -> Set<String> {
        var names: Set<String> = []
        for line in text.split(separator: "\n", omittingEmptySubsequences: true) {
            names.insert(String(line))
        }
        return names
    }

